begin;
create extension if not exists pgtap with schema extensions;
set local search_path=public,extensions;
select plan(8);
select ok(not has_table_privilege('anon','public.analytics_sessions','select'),'no public reads');
select ok(not has_table_privilege('authenticated','public.analytics_page_views','insert'),'no browser writes');
select ok(not has_function_privilege('anon','public.collect_analytics(jsonb)','execute'),'no public RPC');
set local role service_role;
create temporary table test_snapshot as select jsonb_build_object('session_id',gen_random_uuid(),'page_view_id',gen_random_uuid(),'started_at',now()-interval '20 seconds','observed_at',now(),'page_observed_at',now()-interval '20 seconds','page_path','/','landing_page','/','engagement_time_ms',20000,'attribution',jsonb_build_object('source','tiktok','medium','social','campaign','test','attribution_method','utm')) p;
select collect_analytics(p) from test_snapshot;
select collect_analytics(p) from test_snapshot;
select collect_analytics(jsonb_set(p,'{engagement_time_ms}','10000')) from test_snapshot;
select is((select count(*) from analytics_page_views where session_id=(select (p->>'session_id')::uuid from test_snapshot)),1::bigint,'duplicates have one view');
select is((select engagement_time_ms from analytics_sessions where session_id=(select (p->>'session_id')::uuid from test_snapshot)),20000::bigint,'out-of-order does not inflate');
select is((select source from analytics_sessions where session_id=(select (p->>'session_id')::uuid from test_snapshot)),'tiktok','source retained');
select is((select (analytics_report(now()-interval '1 minute',now()+interval '1 minute','tiktok')->'totals'->>'sessions')::integer),1,'server aggregate session count');
select is((select (analytics_report(now()-interval '1 minute',now()+interval '1 minute','tiktok')->'totals'->>'engagement_ms')::numeric),20000::numeric,'session-level average');
select * from finish();
rollback;
